    private void hitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hitungActionPerformed
        // TODO add your handling code here:
        double pj = Double.parseDouble(pajak.getText());
        double gj = Double.parseDouble(gaji.getText());
        int ab = Integer.parseInt(absen.getText());
        int potong = Integer.parseInt(absen.getText());
        double tj;
        double bns;
        
        if(gj >= 2000000 && gj<= 4999999){
            tj = 150000;
        }
        else if (gj >= 5000000 && gj <= 7999999){
            tj = 400000;
        }
        else if (gj >= 8000000 && gj <= 14999999){
            tj = 1000000;
        }
        else if (gj >=15000000 && gj <=30000000){
            tj = 2000000;
        }
        else{
            tj=0;
        }
        
        
        if(ab <= 2){
            bns=500000;
        }
        else if(ab<5){
            bns=300000;
        }
        else{
            bns=0;
        }
        
        if (ab > 5){
            potong = (ab-5)*50000;
        }
        else{
            potong = 0 ;
        }
        
        double pjk = (pj/100)*gj;
        double gjk = gj+bns-potong+tj;
        double gjb = gjk-pjk;
        
            tunjangan.setText(String.valueOf(nf.format(tj)));
            gatot.setText(String.valueOf(nf.format(gjk)));
            gaber.setText(String.valueOf(nf.format(gjb)));
            pajak_2.setText(String.valueOf(nf.format(pjk)));
            bonus.setText(String.valueOf(nf.format(bns)));
            ptg.setText(String.valueOf(nf.format(potong)));

    }//GEN-LAST:event_hitungActionPerformed

