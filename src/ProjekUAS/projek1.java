    public void tampiltabel() {
        try {
 
            String query = "Select * from tbl_karyawan where nip = '"+this.nnip+"'";
            con = DBconfig.sambungkan();
            stm = con.createStatement();
            ResultSet res = stm.executeQuery(query);
            
            if (res.next()){
               String namaa = res.getString("nama");
               String jabatann = res.getString("jabatan");
               String gajii = res.getString("gaji");
               nama.setText(namaa);
               jabatan.setText(jabatann);
               gaji.setText(gajii);
            }
        con.close();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
            System.err.println(e.getMessage());
        }
    }
    
    public void tampilnip() {
        try {
 
            String query = "Select * from tbl_karyawan";
            con = DBconfig.sambungkan();
            stm = con.createStatement();
            ResultSet res = stm.executeQuery(query);
            
            while (res.next()){
                String nip = res.getString("nip");
                pilihnip.addItem(nip);
            }
            con.close();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
            System.err.println(e.getMessage());
        }
    }
    
    
